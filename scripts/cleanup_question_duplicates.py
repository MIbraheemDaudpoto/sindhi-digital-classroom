"""Idempotent question deduplication script with dry-run and apply modes.
Safely collapses duplicate question rows generated by test runs while preserving
all distinct questions, approved status, and quiz_attempts foreign key references.
"""

import argparse
import os
import shutil
import sqlite3
import sys
from datetime import datetime

def analyze_and_deduplicate(db_path: str, dry_run: bool = True):
    print(f"[{'DRY-RUN' if dry_run else 'APPLY'}] Operating on database: {db_path}")
    conn = sqlite3.connect(db_path)
    cur = conn.cursor()

    cur.execute("SELECT count(*) FROM questions")
    total_before = cur.fetchone()[0]

    cur.execute("SELECT count(*) FROM questions WHERE lesson_id = 'lesson-sci-6-1'")
    sci_before = cur.fetchone()[0]

    cur.execute("SELECT count(*) FROM quiz_attempts")
    attempts_before = cur.fetchone()[0]

    # Find which question_ids are referenced in quiz_attempts
    cur.execute("SELECT DISTINCT question_id FROM quiz_attempts WHERE question_id IS NOT NULL")
    referenced_qids = {r[0] for r in cur.fetchall()}
    print(f"Total questions before: {total_before}")
    print(f"lesson-sci-6-1 questions before: {sci_before}")
    print(f"Referenced question IDs in quiz_attempts ({len(referenced_qids)}): {referenced_qids}")

    # Identify duplicate groups for all lessons
    cur.execute("""
        SELECT lesson_id, timestamp_seconds, text_sindhi, COUNT(*), GROUP_CONCAT(id)
        FROM questions
        GROUP BY lesson_id, timestamp_seconds, text_sindhi
        HAVING COUNT(*) > 1
    """)
    duplicate_groups = cur.fetchall()
    print(f"Duplicate groups found: {len(duplicate_groups)}")

    total_duplicates_to_remove = 0
    ids_to_delete = []

    for group in duplicate_groups:
        lesson_id, ts, text, count, ids_concat = group
        all_ids = ids_concat.split(",")
        total_duplicates_to_remove += (count - 1)

        # Determine which ID to keep:
        # Priority 1: Any ID referenced by quiz_attempts
        # Priority 2: Any ID starting with 'q-sci' (handcrafted seed)
        # Priority 3: Earliest created ID (min)
        keep_id = None
        for qid in all_ids:
            if qid in referenced_qids:
                keep_id = qid
                break
        
        if keep_id is None:
            for qid in all_ids:
                if qid.startswith("q-sci-"):
                    keep_id = qid
                    break

        if keep_id is None:
            keep_id = sorted(all_ids)[0]

        for qid in all_ids:
            if qid != keep_id:
                ids_to_delete.append(qid)

    print(f"Rows identified for removal: {len(ids_to_delete)}")
    print(f"Rows that will remain: {total_before - len(ids_to_delete)}")

    if not dry_run and ids_to_delete:
        print("Executing deletion in transaction...")
        # Delete in chunks to avoid variable limits
        chunk_size = 500
        for i in range(0, len(ids_to_delete), chunk_size):
            chunk = ids_to_delete[i:i + chunk_size]
            placeholders = ",".join("?" for _ in chunk)
            cur.execute(f"DELETE FROM questions WHERE id IN ({placeholders})", chunk)

        conn.commit()
        print("Deletion committed successfully.")

        # Run vacuum to reclaim disk space
        print("Running VACUUM to reclaim space...")
        conn.execute("VACUUM")
        conn.commit()

        # Check counts after
        cur.execute("SELECT count(*) FROM questions")
        total_after = cur.fetchone()[0]
        cur.execute("SELECT count(*) FROM questions WHERE lesson_id = 'lesson-sci-6-1'")
        sci_after = cur.fetchone()[0]
        cur.execute("SELECT count(*) FROM quiz_attempts")
        attempts_after = cur.fetchone()[0]

        print(f"Total questions after: {total_after}")
        print(f"lesson-sci-6-1 questions after: {sci_after}")
        print(f"quiz_attempts after: {attempts_after}")
        assert attempts_before == attempts_after, "Foreign keys in quiz_attempts corrupted!"
        print("Verification passed: Integrity intact.")

    conn.close()

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Clean up duplicate questions safely.")
    parser.add_argument("--db", type=str, default="data/sdc_platform.db", help="Path to database")
    parser.add_argument("--apply", action="store_true", help="Apply changes (default is dry-run)")
    args = parser.parse_args()

    analyze_and_deduplicate(args.db, dry_run=not args.apply)

